import fs from 'node:fs';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import access from '../api/_lib/privateAccess.js';
import { recordsFor } from '../src/trainingSync.mjs';
import { targetProgress, trainingDay } from '../src/flexible.mjs';
Object.assign(process.env,JSON.parse(fs.readFileSync(new URL('../.env.server.local',import.meta.url))));
const origin='http://127.0.0.1:5174';
const headers={Cookie:`${access.COOKIE}=${access.sign('session',3600)}`,Origin:origin,'Content-Type':'application/json'};
const read=async()=>{const r=await fetch(`${origin}/api/training`,{headers});const d=await r.json();assert.equal(r.status,200,JSON.stringify(d));return d.state;};
const save=async operations=>{const r=await fetch(`${origin}/api/training`,{method:'POST',headers,body:JSON.stringify({operations})});const d=await r.json();assert.equal(r.status,200,JSON.stringify(d));assert.equal(d.error,undefined,JSON.stringify(d));assert.equal(d.acknowledged.length,operations.length);};
const operation=(entity,recordId,changes,base,create=false)=>({id:crypto.randomUUID(),entity,recordId,changes,base,create});
for(const endpoint of ['config','exercises','routines','workouts','training']) assert.equal((await fetch(`${origin}/api/${endpoint}`)).status,401,`Unauthenticated ${endpoint}`);
let state=await read();
const testSets=state.sets.filter(set=>set.note==='Temporary deployment verification — remove before release');
assert.equal(testSets.length,2,'Expected only the two marked browser verification sets');
const chest=state.targets.find(target=>target.name==='Chest press');
const day=trainingDay(new Date(),state.timeZone);
assert.equal(targetProgress(state,chest,day).occasions,1);
const record=recordsFor(state,'sets').find(set=>set.id===testSets[0].id);
const {id,...changes}=record;
await save([operation('sets',id,changes,Object.fromEntries(Object.keys(changes).map(key=>[key,null])),true)]);
state=await read();assert.equal(state.sets.length,2,'A retry must not duplicate a working set');
await save([operation('sets',id,{deleted:true},{deleted:false})]);
state=await read();assert.equal(targetProgress(state,chest,day).occasions,0);
await save([operation('sets',id,changes,Object.fromEntries(Object.keys(changes).map(key=>[key,null])),true)]);
state=await read();assert.equal(targetProgress(state,chest,day).occasions,1,'Undo must restore the original set ID and credit');
const lateral=state.exercises.find(exercise=>exercise.id==='2b3fe23d-5e3c-802f-b092-f8f679d3e372');
const assigned=recordsFor(state,'assignments').find(item=>item.id===lateral.id).machineIds;
assert.equal(assigned.length,3);
await save([operation('assignments',lateral.id,{machineIds:assigned.slice(0,2)},{machineIds:assigned})]);
state=await read();assert.equal(recordsFor(state,'assignments').find(item=>item.id===lateral.id).machineIds.length,2);
await save([operation('assignments',lateral.id,{machineIds:assigned},{machineIds:assigned.slice(0,2)})]);
await save(testSets.map(set=>operation('sets',set.id,{deleted:true},{deleted:false})));
const sessionId=testSets[0].sessionId;
await save([operation('sessions',sessionId,{endedAt:new Date().toISOString(),restUntil:0},{endedAt:null,restUntil:state.sessions.find(session=>session.id===sessionId).restUntil})]);
state=await read();assert.equal(state.sets.length,0);assert.equal(targetProgress(state,chest,day).occasions,0);
fs.writeFileSync('/tmp/fitness-verification-records.json',JSON.stringify({setIds:testSets.map(set=>set.id),sessionIds:[sessionId]}),{mode:0o600});
console.log('Passed: private APIs, live logging/reload, one occasion after two sets, idempotent retry, remove/undo, equipment unlink/relink. Verification sets removed.');
